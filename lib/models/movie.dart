class Movie {
  final String title;
  final String genre;
  final String director;
  final String actors;
  final String rating;
  final String poster;
  final String summary;
  final bool isNowPlaying;

  Movie({
    required this.title,
    required this.genre,
    required this.director,
    required this.actors,
    required this.rating,
    required this.poster,
    required this.summary,
    required this.isNowPlaying,
  });
}
